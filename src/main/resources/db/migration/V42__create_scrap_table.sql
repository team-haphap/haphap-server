-- 공고 찜하기. (user, posting)당 한 건 — 중복 찜은 유니크 제약 + INSERT ON CONFLICT DO NOTHING으로 멱등 처리
CREATE TABLE scrap (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    user_id    BIGINT NOT NULL,
    posting_id BIGINT NOT NULL,
    CONSTRAINT uk_scrap_user_posting UNIQUE (user_id, posting_id),
    CONSTRAINT fk_scrap_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_scrap_posting FOREIGN KEY (posting_id) REFERENCES posting (id)
);

-- [내가 찜한 공고] 최신순 조회용
CREATE INDEX idx_scrap_user_created ON scrap (user_id, created_at DESC);
